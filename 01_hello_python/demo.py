"""
第 01 章：第一个 Python 程序

本文件演示：
1. 注释的三种写法
2. Python 用缩进表示代码块（非常重要）
3. print() 如何输出内容
"""

# ---------- 1. 单行注释 ----------
# 以 # 开头的内容会被解释器忽略，用来给人看。

print("Hello, Python")  # 也可以写在代码后面，解释这一行在做什么

# ---------- 2. 多行注释 / 文档字符串 ----------
# 三个引号包起来的文字常用来写较长说明。
# 放在文件或函数开头时，也叫 docstring（文档字符串）。

"""
这是一段多行说明。
运行程序时，单独放在这里的字符串不会产生可见输出，
但也不会报错。
"""

# ---------- 3. print 的基本用法 ----------
print("一行文字")
print("姓名:", "张三")          # 多个参数默认用空格隔开
print("A", "B", "C", sep="-")  # sep 指定分隔符
print("不换行", end="")        # end 默认是换行符 \n，改成空字符串就不会换行
print("接在上一句后面")

# ---------- 4. 缩进：Python 用空格表示从属关系 ----------
# 推荐每层缩进 4 个空格。同一层级必须对齐，否则会 IndentationError。
score = 90
if score >= 60:
    # 这一行比 if 多缩进 4 格，表示它属于 if 这个代码块
    print("及格")
    print("继续加油")
# 这一行退回到与 if 对齐，表示已经离开 if 代码块
print("程序结束")
